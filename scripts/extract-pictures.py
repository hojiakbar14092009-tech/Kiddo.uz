"""Copies the pictures Kiddo uses from Microsoft's Fluent Emoji set (MIT licence).

Every emoji used for letters, numbers, stickers and robot clothes becomes a
standalone SVG in public/pictures/, and src/content/pictures.ts maps each emoji
to its file. Run again after adding a new word or sticker:

    npm pack @iconify-json/fluent-emoji && tar xzf iconify-json-fluent-emoji-*.tgz
    python3 scripts/extract-pictures.py package/icons.json
"""
import glob, json, re, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [*glob.glob(str(ROOT / 'src/content/**/*.ts'), recursive=True),
           str(ROOT / 'src/features/stickers/stickers.ts'),
           str(ROOT / 'src/features/shop/outfits.ts')]
# Unicode names that differ from the Fluent Emoji file names.
OVERRIDES = {
    '☀️': 'sun', '⭐': 'star', '🐹': 'hamster', '🐼': 'panda', '👓': 'glasses',
    '🖊️': 'pen', '🚂': 'locomotive', '🚩': 'triangular-flag', '🤖': 'robot',
    '🦁': 'lion', '🦄': 'unicorn', '🦊': 'fox', '🦒': 'giraffe', '🦓': 'zebra',
}

def main(icons_path: str) -> None:
    data = json.load(open(icons_path))
    icons, aliases = data['icons'], data.get('aliases', {})
    text = ''.join(Path(f).read_text() for f in SOURCES if not f.endswith('pictures.ts'))
    emojis = sorted({e for e in re.findall(r"'([^'\w\s]{1,4})'", text) if any(ord(c) > 0x2000 for c in e)})
    out = ROOT / 'public/pictures'
    out.mkdir(parents=True, exist_ok=True)
    mapping = {}
    for emoji in emojis:
        name = OVERRIDES.get(emoji) or unicodedata.name(emoji.replace('️', '')).lower().replace(' ', '-')
        name = aliases.get(name, {}).get('parent', name)
        icon = icons.get(name)
        if not icon:
            sys.exit(f'No Fluent Emoji picture for {emoji} ({name}); add it to OVERRIDES')
        w, h = icon.get('width', data.get('width', 32)), icon.get('height', data.get('height', 32))
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">{icon["body"]}</svg>'
        (out / f'{name}.svg').write_text(svg)
        mapping[emoji] = name
    lines = ['/* Generated by scripts/extract-pictures.py – do not edit by hand. */', '',
             '/** Emoji → picture file in /pictures (Fluent Emoji, © Microsoft, MIT licence). */',
             'export const PICTURE_FILES: Readonly<Record<string, string>> = {']
    lines += [f"  '{e}': '{n}'," for e, n in mapping.items()]
    lines += ['}', '']
    (ROOT / 'src/content/pictures.ts').write_text('\n'.join(lines))
    print(f'{len(mapping)} pictures written')

if __name__ == '__main__':
    main(sys.argv[1])
